from array import array

print(" ")
# b = Signed char
a1 = array('b', [1, 2, 3])
print("Signed char:", a1)
print(type(a1))
print(" ")

# B = Unsigned char
a2 = array('B', [1, 2, 3])
print("Unsigned char:", a2)
print(" ")


# u = Unicode character
a3 = array('u', 'ABC')
print("Unicode character:", a3)
print(" ")

# h = Signed short integer
a4 = array('h', [1, 2, 3])
print("Signed short:", a4)
print(" ")

# H = Unsigned short integer
a5 = array('H', [1, 2, 3])
print("Unsigned short:", a5)
print(" ")

# i = Signed integer
a6 = array('i', [10, 20, 30])
print("Signed integer:", a6)
print(" ")

# I = Unsigned integer
a7 = array('I', [10, 20, 30])
print("Unsigned integer:", a7)
print(" ")

# l = Signed long integer
a8 = array('l', [10, 20, 30])
print("Signed long:", a8)
print(" ")

# L = Unsigned long integer
a9 = array('L', [10, 20, 30])
print("Unsigned long:", a9)
print(" ")

# q = Signed long long integer
a10 = array('q', [10, 20, 30])
print("Signed long long:", a10)
print(" ")

# Q = Unsigned long long integer
a11 = array('Q', [10, 20, 30])
print("Unsigned long long:", a11)
print(" ")

# f = Float
a12 = array('f', [1.1, 2.2, 3.3])
print("Float:", a12)
print(" ")

# d = Double
a13 = array('d', [1.1, 2.2, 3.3])
print("Double:", a13)
print(" ")