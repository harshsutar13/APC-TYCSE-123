# 8. Create a dictionary and display:
# • All keys 
# • All values 
# • All key-value pairs

dict1 = {
    "a": 10,
    "b": 20,
    "c": 30,
    "d": 40
}

print("Dictionary:", dict1)

print("\nAll keys:")
print(list(dict1.keys()))

print("\nAll values:")
print(list(dict1.values()))

print("\nAll key-value pairs:")
print(list(dict1.items()))
